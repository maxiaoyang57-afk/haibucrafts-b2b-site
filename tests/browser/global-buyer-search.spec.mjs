import { test, expect } from '@playwright/test';
test('global search finds products by code, material and use and preserves product links', async ({page,context}) => {
  await context.route('**/*', route => route.request().url().startsWith('http://127.0.0.1:4173/') && ['GET','HEAD'].includes(route.request().method()) ? route.continue() : route.abort());
  await page.goto('/products/');
  const box=page.locator('#catalog-search-input'), status=page.locator('#catalog-search-status'), cards=page.locator('#catalog-search-results a');
  await box.fill('slm26529');
  await expect(status).toContainText('1 of 1');
  await expect(cards.first()).toContainText('SLM26529');
  await expect(cards.first()).toHaveAttribute('href', /slm26529/);
  await box.fill('resin');
  await expect(cards.first()).toBeVisible();
  await expect(status).toContainText('matching products');
  await box.fill('phone case');
  await expect(cards.first()).toBeVisible();
  await box.fill('xyznonexistent123');
  await expect(status).toContainText('No matching products');
  await expect(page.locator('#catalog-search-help')).toBeVisible();
  await box.fill('');
  await expect(cards).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
});
